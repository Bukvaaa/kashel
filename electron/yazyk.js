let язык = 'ru'

const ЯЗЫКИ = ['ru', 'en', 'sr', 'sr-Latn']
function поставить(я) {
  язык = ЯЗЫКИ.includes(я) ? я : 'ru'
}

/** Фраза на языке оболочки. Незнакомая остаётся как есть — русской, а не пустой. */
function м(фраза) {
  if (typeof фраза !== 'string' || язык === 'ru') return фраза
  if (язык === 'sr' || язык === 'sr-Latn') {
    let с = SR[фраза]
    if (!с) for (const [ru, sr] of SR_НАЧАЛА) if (фраза.startsWith(ru)) { с = sr + фраза.slice(ru.length); break }
    if (!с) return фраза
    return язык === 'sr-Latn' ? латиница(с) : с
  }
  if (EN[фраза]) return EN[фраза]
  for (const [ru, en] of EN_НАЧАЛА) if (фраза.startsWith(ru)) return en + фраза.slice(ru.length)
  return фраза
}

