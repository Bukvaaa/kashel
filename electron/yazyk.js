const ЛАТ = {
  а: 'a', б: 'b', в: 'v', г: 'g', д: 'd', ђ: 'đ', е: 'e', ж: 'ž', з: 'z', и: 'i', ј: 'j', к: 'k', л: 'l', љ: 'lj',
  м: 'm', н: 'n', њ: 'nj', о: 'o', п: 'p', р: 'r', с: 's', т: 't', ћ: 'ć', у: 'u', ф: 'f', х: 'h', ц: 'c', ч: 'č',
  џ: 'dž', ш: 'š',
}
/** Сербская кириллица → латиница (то же, что src/i18n/latinica.ts, в коротком виде). */
function латиница(s) {
  let r = ''
  for (const ч of s) {
    const м = ч.toLowerCase()
    const л = ЛАТ[м]
    if (л === undefined) r += ч
    else r += ч === м ? л : л[0].toUpperCase() + л.slice(1)
  }
  return r
}

