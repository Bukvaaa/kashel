/*
 * Сербская кириллица → латиница. Латинский перевод не хранится отдельно:
 * он получается из кириллического буква в букву (у сербского это взаимно
 * однозначно, кроме диграфов lj, nj, dž). Места {0} и всё некириллическое
 * остаются как есть. Русские буквы, которые могли остаться в именах,
 * передаются по-сербски же, чтобы латиница не пестрела кириллицей.
 */
const БУКВЫ: Record<string, string> = {
  а: 'a', б: 'b', в: 'v', г: 'g', д: 'd', ђ: 'đ', е: 'e', ж: 'ž', з: 'z', и: 'i', ј: 'j', к: 'k', л: 'l', љ: 'lj',
  м: 'm', н: 'n', њ: 'nj', о: 'o', п: 'p', р: 'r', с: 's', т: 't', ћ: 'ć', у: 'u', ф: 'f', х: 'h', ц: 'c', ч: 'č',
  џ: 'dž', ш: 'š',
  // русские
  я: 'ja', ю: 'ju', ё: 'jo', й: 'j', ы: 'i', э: 'e', щ: 'šč', ъ: '', ь: '', ѣ: 'e', і: 'i', ѳ: 'f', ѵ: 'i',
}

export function латиница(s: string): string {
  let r = ''
  for (let i = 0; i < s.length; i++) {
    const ч = s[i]
    const м = ч.toLowerCase()
    const л = БУКВЫ[м]
    if (л === undefined) { r += ч; continue }
    if (ч === м || !л) { r += л; continue }
    // Заглавная: диграф целиком заглавный, если рядом тоже заглавные (LJUBAV), иначе Lj.
    const след = s[i + 1] ?? ''
    const пред = s[i - 1] ?? ''
    const кругомЗаглавные = (след && след !== след.toLowerCase()) || (пред && пред !== пред.toLowerCase() && !след)
    r += л.length > 1 && !кругомЗаглавные ? л[0].toUpperCase() + л.slice(1) : л.toUpperCase()
  }
  return r
}
